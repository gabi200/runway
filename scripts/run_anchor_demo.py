"""On-chain anchoring evidence: publish the audit head to an EVM chain and catch a forged history with it.

Needs a running EVM node and a funded key, for example a local Anvil dev chain:

    anvil &
    RUNWAY_EVM_RPC_URL=http://127.0.0.1:8545 RUNWAY_EVM_PRIVATE_KEY=<funded key> \\
        .venv/bin/python scripts/run_anchor_demo.py

Writes docs/execution_logs/anchor_receipt.json and anchor_run.md. Never writes the key or the RPC URL.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path
from tempfile import TemporaryDirectory

if __package__ in {None, ""}:
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from agent.orchestrator import Agent  # noqa: E402
from audit import anchor  # noqa: E402
from common import db  # noqa: E402
from data.generate import generate  # noqa: E402
from redteam.console import audit_rewrite  # noqa: E402

REPO = Path(__file__).resolve().parents[1]


def cli(command: str, env: dict) -> tuple[int, dict]:
    run = subprocess.run([sys.executable, "-m", "audit.anchor", command], cwd=REPO, env=env,
                         capture_output=True, text=True, timeout=300)
    if run.returncode not in (0, 1):
        raise SystemExit(f"audit.anchor {command} failed:\n{run.stderr[-2000:]}")
    return run.returncode, json.loads(run.stdout)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=REPO / "docs" / "execution_logs")
    args = parser.parse_args()
    if not (os.getenv("RUNWAY_EVM_RPC_URL") and os.getenv("RUNWAY_EVM_PRIVATE_KEY")):
        raise SystemExit("Set RUNWAY_EVM_RPC_URL and RUNWAY_EVM_PRIVATE_KEY (a funded key on that chain).")
    with TemporaryDirectory(prefix="runway-anchor-") as tmp:
        root = Path(tmp)
        env = {**os.environ, "RUNWAY_DB": str(root / "demo.db"), "RUNWAY_VAR_DIR": str(root / "var"),
               "RUNWAY_LLM": "offline", "RUNWAY_ANCHOR": "evm"}
        os.environ.update({k: env[k] for k in ("RUNWAY_DB", "RUNWAY_VAR_DIR", "RUNWAY_LLM", "RUNWAY_ANCHOR")})
        db.reset_engines()
        generate(out_dir=root / "sample")
        Agent(db.session_scope).monday_brief()  # real activity in the audit log
        db.reset_engines()
        _, receipt = cli("publish", env)
        code, report = cli("verify", env)
        backend = anchor.get_backend()
        chain_id = int(backend._rpc("eth_chainId", []), 16)
        tx = backend._rpc("eth_getTransactionByHash", [receipt["ref"]])
        payload = backend.fetch(receipt["ref"])
        forged = audit_rewrite(db.db_path(), "forge", backend)
        db.reset_engines()
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "anchor_receipt.json").write_text(json.dumps(receipt, indent=2) + "\n")
    lines = [
        "# On-chain anchoring evidence", "",
        f"Chain id {chain_id} (a local Anvil dev chain unless stated otherwise). Generated by "
        "`scripts/run_anchor_demo.py` on a fresh seed-42 workspace after the offline Monday brief.", "",
        "## 1. Publish (`python -m audit.anchor publish`)", "", "```json", json.dumps(receipt, indent=2), "```", "",
        "## 2. The transaction on chain", "",
        f"- hash `{tx['hash']}`, block {int(tx['blockNumber'], 16)}, from `{tx['from']}` to `{tx['to']}`, value 0",
        f"- calldata decoded: `{payload}`", "",
        f"## 3. Verify (`python -m audit.anchor verify`, exit code {code})", "",
        "```json", json.dumps(report, indent=2), "```", "",
        "## 4. Insider forgery on a copy of the database, checked against the chain", "",
        f"Verdict: **{forged.verdict}** ({forged.scenario})", "",
        *[f"- {step.layer}: {step.outcome}. {step.detail}" for step in forged.steps], "",
    ]
    (args.out / "anchor_run.md").write_text("\n".join(lines))
    print(json.dumps({"tx": receipt["ref"], "verify": report["status"], "forged_copy": forged.verdict}, indent=2))


if __name__ == "__main__":
    main()
