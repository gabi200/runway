"""Invoice details, a PDF copy rendered from the ledger, and invoice references in text."""

from __future__ import annotations

import io
import json
import re
from xml.sax.saxutils import escape

from sqlmodel import Session, select

from agent.financing import ledger_money
from agent.outbox import COMPANY
from common.db import Counterparty, Document, Invoice, OutboxEmail, Payment, get_today

# Candidate ids and numbers ("AR-1007", "LUM-2025-0007"); only those found in the ledger count.
_TOKEN = re.compile(r"\b[A-Z][A-Z0-9]*(?:-[A-Z0-9]+)+\b")


def find_invoice_refs(session: Session, text: str) -> list[str]:
    """Ids of the invoices that `text` names by id or number, in order of first mention."""
    tokens = list(dict.fromkeys(_TOKEN.findall(text or "")))
    if not tokens:
        return []
    by_key = {}
    for inv in session.exec(select(Invoice)):
        by_key[inv.id] = by_key[inv.number] = inv.id
    return list(dict.fromkeys(by_key[t] for t in tokens if t in by_key))


def invoice_details(session: Session, invoice_id: str) -> dict | None:
    """Everything the app shows about one invoice, read from the ledger (None if unknown)."""
    inv = session.get(Invoice, invoice_id)
    if inv is None:
        return None
    today = get_today(session)
    cp = session.get(Counterparty, inv.counterparty_id)
    doc = session.get(Document, inv.document_id) if inv.document_id else None
    overdue = inv.status == "open" and inv.due_date < today
    reminders = session.exec(select(OutboxEmail).where(OutboxEmail.invoice_id == inv.id,
                                                       OutboxEmail.kind == "reminder")
                             .order_by(OutboxEmail.sent_at)).all()
    payments = session.exec(select(Payment).where(Payment.invoice_id == inv.id).order_by(Payment.execute_date)).all()
    return {
        "id": inv.id, "number": inv.number, "direction": inv.direction,
        "kind": "Customer invoice (money owed to us)" if inv.direction == "AR" else "Supplier invoice (money we owe)",
        "counterparty": cp.name if cp else inv.counterparty_id, "counterparty_email": cp.email if cp else None,
        "issue_date": inv.issue_date.isoformat(), "due_date": inv.due_date.isoformat(),
        "amount_cents": inv.amount_cents, "vat_cents": inv.vat_cents, "net_cents": inv.amount_cents - inv.vat_cents,
        "currency": inv.currency, "status": inv.status,
        "paid_date": inv.paid_date.isoformat() if inv.paid_date else None,
        "overdue": overdue, "days_overdue": (today - inv.due_date).days if overdue else 0,
        "critical": inv.critical, "can_remind": inv.direction == "AR" and overdue,
        "reminders": [{"id": m.id, "sent_at": m.sent_at.date().isoformat(), "subject": m.subject} for m in reminders],
        "payments": [{"id": p.id, "execute_date": p.execute_date.isoformat(), "status": p.status,
                      "amount_cents": p.amount_cents} for p in payments],
        "document": ({"id": doc.id, "filename": doc.filename, "flagged": doc.flagged and not doc.cleared,
                      "invoice_ids": json.loads(doc.invoice_ids)} if doc else None),
    }


def invoice_pdf(session: Session, invoice_id: str) -> bytes:
    """A PDF copy of the invoice rendered from the ledger row (not the original document)."""
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

    d = invoice_details(session, invoice_id)
    if d is None:
        raise ValueError(f"invoice {invoice_id!r} not found")
    st = getSampleStyleSheet()
    cell = ParagraphStyle("cell", parent=st["Normal"], fontSize=10, leading=12)

    def money(cents: int) -> str:
        return ledger_money(cents, d["currency"])

    def table(rows: list[tuple[str, str]]) -> Table:
        t = Table([(k, Paragraph(escape(v), cell)) for k, v in rows], colWidths=[50 * mm, 109 * mm])
        t.setStyle(TableStyle([("FONTSIZE", (0, 0), (-1, -1), 10), ("VALIGN", (0, 0), (-1, -1), "TOP"),
                               ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
                               ("LINEBELOW", (0, 0), (-1, -1), 0.25, "#cccccc")]))
        return t

    issuer, billed = (COMPANY, d["counterparty"]) if d["direction"] == "AR" else (d["counterparty"], COMPANY)
    status = ("Paid on " + d["paid_date"] if d["status"] == "paid" else
              f"Open, {d['days_overdue']} day(s) overdue" if d["overdue"] else "Open, not yet due")
    story = [
        Paragraph(escape(f"Invoice {d['number']}"), st["Title"]),
        Paragraph(escape(f"Copy generated by Runway from the ledger on {get_today(session).isoformat()}. "
                         "This is not the original document."), st["Normal"]),
        Spacer(1, 6 * mm),
        table([("Issued by", issuer), ("Billed to", billed), ("Type", d["kind"]), ("Ledger id", d["id"]),
               ("Invoice date", d["issue_date"]), ("Due date", d["due_date"]), ("Status", status)]),
        Spacer(1, 6 * mm), Paragraph("Amounts", st["Heading2"]),
        table([("Net amount", money(d["net_cents"])), ("VAT", money(d["vat_cents"])),
               ("Total due", money(d["amount_cents"]))]),
    ]
    if d["payments"]:
        story += [Spacer(1, 6 * mm), Paragraph("Payments", st["Heading2"]),
                  table([(p["id"], f"{money(p['amount_cents'])} on {p['execute_date']} ({p['status']})")
                         for p in d["payments"]])]
    if d["reminders"]:
        story += [Spacer(1, 6 * mm), Paragraph("Reminders sent", st["Heading2"]),
                  table([(m["id"], f"{m['sent_at']}: {m['subject']}") for m in d["reminders"]])]
    buf = io.BytesIO()
    SimpleDocTemplate(buf, pagesize=A4, title=f"Invoice {d['number']}").build(story)
    return buf.getvalue()
